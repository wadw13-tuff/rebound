const exerciseById = new Map(
  exercises.map((exercise) => [exercise.id, exercise]),
);

/**
 * Return only explicitly approved substitutions. A candidate must retain the
 * movement pattern, be available with the selected equipment, and avoid the
 * reported area and every paused area. An unknown source has no candidates.
 */
export function approvedCandidates(
  exerciseId: string,
  area: string,
  equipment: Equipment,
  pausedAreas: string[] = [],
): Exercise[] {
  const source = exerciseById.get(exerciseId);
  if (!source || pausedAreas.includes("all")) return [];

  const excludedAreas = new Set([area, ...pausedAreas]);
  return source.swapIds
    .map((swapId) => exerciseById.get(swapId))
    .filter((candidate): candidate is Exercise => Boolean(candidate))
    .filter((candidate) => candidate.pattern === source.pattern)
    .filter((candidate) => candidate.equipment.includes(equipment))
    .filter(
      (candidate) =>
        !candidate.loadedAreas.some((loadedArea) =>
          excludedAreas.has(loadedArea),
        ),
    );
}

export function findExercise(exerciseId: string): Exercise | undefined {
  return exerciseById.get(exerciseId);
}
